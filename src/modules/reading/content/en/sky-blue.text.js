      text: `Look up on a sunny day. The sky is blue. But why? Why not green, or white, or purple? Many children ask this question, and many adults cannot answer it.

Light from the sun looks white to us. But white light is really a mix of many colours: red, orange, yellow, green, blue and violet. You can see these colours in a rainbow.

Light travels in waves. Each colour has a different wave. Red light has long, lazy waves. Blue light has short, quick waves.

The air around the Earth is full of very small pieces of gas. They are much too small to see. When sunlight enters the air, it hits these small pieces.

Short blue waves hit the pieces of gas more often than long red waves. So blue light changes direction again and again. It goes everywhere across the sky. Scientists call this "scattering".

Because blue light comes to our eyes from every part of the sky, the whole sky looks blue.

What about sunsets? In the evening the sun is low. Its light must travel through much more air to reach us. Most of the blue light scatters away before it arrives. The long red and orange waves are left, and the sky turns red and gold.

And on the Moon? The Moon has no air, so there is nothing to scatter the light. Even in the daytime, the sky on the Moon is black.`,
